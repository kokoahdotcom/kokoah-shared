/**
 * Agent attestations: the signer service's proof that it generated a server agent (`kokoah-bot`) for a user.
 *
 * The backend relays agent requests between the browser and the isolated signer service, so an agent address the
 * browser receives could have been swapped by the backend for one whose key the attacker holds. The signer service
 * signs each agent it reports with an attestation key of its own (EIP-712); the browser checks that signature against
 * the attester address built into its release, together with the user, network, name, expiry and a fresh challenge the
 * browser picked, before it asks the main wallet to approve the agent.
 *
 * @module
 */
import { type Hex, recoverTypedDataAddress } from "viem";

/** EIP-712 domain name of agent attestations (no chain id: `network` binds the attestation to one network). */
export const AGENT_ATTESTATION_DOMAIN_NAME = "Kokoah Signer Attestation";
/** EIP-712 domain version of agent attestations. */
export const AGENT_ATTESTATION_VERSION = "1";

/** EIP-712 types of an agent attestation. */
export const AGENT_ATTESTATION_TYPES = {
  AgentAttestation: [
    { name: "user", type: "address" },
    { name: "agent", type: "address" },
    { name: "network", type: "string" },
    { name: "agentName", type: "string" },
    { name: "validUntil", type: "uint64" },
    { name: "challenge", type: "bytes32" },
    { name: "issuedAt", type: "uint64" },
  ],
} as const;

/** What an attestation says: this agent was generated by the signer service for this user. */
export interface AgentAttestationFields {
  /** The main wallet the agent belongs to. */
  user: `0x${string}`;
  /** The agent's address. */
  agent: `0x${string}`;
  network: "Mainnet" | "Testnet";
  /** The agent name without HL's `valid_until` suffix, e.g. `kokoah-bot`. */
  agentName: string;
  /** The expiry the signer service issued (ms). */
  validUntil: number;
  /** The browser's fresh 32-byte challenge. */
  challenge: `0x${string}`;
  /** When the signer service signed (ms). */
  issuedAt: number;
}

/** An attestation as the signer service returns it. */
export interface AgentAttestation {
  issuedAt: number;
  /** 65-byte EIP-712 signature by the signer service's attestation key. */
  signature: `0x${string}`;
}

const ADDRESS = /^0x[0-9a-fA-F]{40}$/;
const CHALLENGE = /^0x[0-9a-fA-F]{64}$/;
const SIGNATURE = /^0x[0-9a-fA-F]{130}$/;
const ZERO = "0x0000000000000000000000000000000000000000";

/** A well-formed attestation challenge: 32 bytes of hex. */
export function isAttestationChallenge(value: unknown): value is `0x${string}` {
  return typeof value === "string" && CHALLENGE.test(value);
}

/** Builds the EIP-712 typed data of an attestation (viem `signTypedData` shape). Addresses are lowercased. */
export function buildAgentAttestationTypedData(fields: AgentAttestationFields) {
  if (!ADDRESS.test(fields.user) || fields.user.toLowerCase() === ZERO) throw new RangeError("user must be a nonzero 20-byte hex address");
  if (!ADDRESS.test(fields.agent) || fields.agent.toLowerCase() === ZERO) throw new RangeError("agent must be a nonzero 20-byte hex address");
  if (fields.network !== "Mainnet" && fields.network !== "Testnet") throw new RangeError("network must be Mainnet or Testnet");
  if (fields.agentName.length === 0 || fields.agentName.length > 64) throw new RangeError("agentName must be 1 to 64 characters");
  if (!Number.isSafeInteger(fields.validUntil) || fields.validUntil <= 0) throw new RangeError("validUntil must be a positive integer");
  if (!Number.isSafeInteger(fields.issuedAt) || fields.issuedAt <= 0) throw new RangeError("issuedAt must be a positive integer");
  if (!isAttestationChallenge(fields.challenge)) throw new RangeError("challenge must be 32 bytes of hex");
  return {
    domain: { name: AGENT_ATTESTATION_DOMAIN_NAME, version: AGENT_ATTESTATION_VERSION },
    types: { AgentAttestation: AGENT_ATTESTATION_TYPES.AgentAttestation.map((f) => ({ name: f.name, type: f.type })) },
    primaryType: "AgentAttestation" as const,
    message: {
      user: fields.user.toLowerCase() as `0x${string}`,
      agent: fields.agent.toLowerCase() as `0x${string}`,
      network: fields.network,
      agentName: fields.agentName,
      validUntil: BigInt(fields.validUntil),
      challenge: fields.challenge.toLowerCase() as Hex,
      issuedAt: BigInt(fields.issuedAt),
    },
  };
}

/** How long after `issuedAt` an attestation is accepted, and how far ahead of the browser's clock it may be. */
export const AGENT_ATTESTATION_MAX_AGE_MS = 10 * 60_000;
export const AGENT_ATTESTATION_MAX_SKEW_MS = 5 * 60_000;

/**
 * Why an attestation doesn't prove that the signer service generated `agent` for `expected.user`, or null when it
 * does: the signature must recover to one of `expected.attesters` over exactly these fields and the caller's own
 * challenge, and `issuedAt` must be recent by the caller's clock. Never throws.
 */
export async function agentAttestationProblem(
  attestation: unknown,
  agent: { agentAddress: string; agentName: string; validUntil: number },
  expected: {
    attesters: readonly string[];
    user: string;
    network: "Mainnet" | "Testnet";
    challenge: `0x${string}`;
    now: number;
  },
): Promise<string | null> {
  if (expected.attesters.length === 0) return "No signer attestation key is configured.";
  if (typeof attestation !== "object" || attestation === null) return "The key has no signer attestation.";
  const { issuedAt, signature } = attestation as Partial<AgentAttestation>;
  if (typeof signature !== "string" || !SIGNATURE.test(signature)) return "The signer attestation is malformed.";
  if (typeof issuedAt !== "number" || !Number.isSafeInteger(issuedAt)) return "The signer attestation is malformed.";
  if (issuedAt > expected.now + AGENT_ATTESTATION_MAX_SKEW_MS || issuedAt < expected.now - AGENT_ATTESTATION_MAX_AGE_MS) {
    return "The signer attestation is not recent.";
  }
  let signer: string;
  try {
    const typed = buildAgentAttestationTypedData({
      user: expected.user as `0x${string}`,
      agent: agent.agentAddress as `0x${string}`,
      network: expected.network,
      agentName: agent.agentName,
      validUntil: agent.validUntil,
      challenge: expected.challenge,
      issuedAt,
    });
    signer = await recoverTypedDataAddress({ ...typed, signature });
  } catch {
    return "The signer attestation is malformed.";
  }
  const attesters = new Set(expected.attesters.map((a) => a.toLowerCase()));
  return attesters.has(signer.toLowerCase()) ? null : "The signer attestation was not made by Kokoah's signer.";
}
